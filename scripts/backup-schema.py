"""Writes web/src/dc/backup-schema.sql: the database of a fresh profile of the pinned
deltachat-rpc-server (e2e/requirements.txt), which Kitepost fills when exporting a backup.

Usage: work/venv/bin/python -I scripts/backup-schema.py
"""

import sqlite3
import sys
import tempfile
from pathlib import Path

from deltachat_rpc_client import DeltaChat, Rpc

OUT = Path(__file__).resolve().parent.parent / "web/src/dc/backup-schema.sql"

with tempfile.TemporaryDirectory() as tmp:
    rpc_path = str(Path(sys.executable).parent / "deltachat-rpc-server")
    with Rpc(accounts_dir=tmp, rpc_server_path=rpc_path) as rpc:
        DeltaChat(rpc).add_account()
        version = rpc.get_system_info()["deltachat_core_version"]
    db = sqlite3.connect(next(Path(tmp).glob("*/dc.db")))
    lines = [line for line in db.iterdump() if line not in ("BEGIN TRANSACTION;", "COMMIT;")]
    db.close()

OUT.write_text(f"-- Fresh profile of Delta Chat core {version}, generated by scripts/backup-schema.py.\n" + "\n".join(lines) + "\n")
print(f"{OUT}: core {version}, {len(lines)} statements")
